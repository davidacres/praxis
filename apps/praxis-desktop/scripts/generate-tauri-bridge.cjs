#!/usr/bin/env node
// The preload is the desktop contract map during the hybrid migration. Generate
// a browser-safe factory, plus an audit manifest, rather than maintain two maps.
const fs = require('node:fs');
const path = require('node:path');
const parser = require('@babel/parser');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(__dirname, 'contract/preload.ts'), 'utf8');
const tree = parser.parse(source, { sourceType: 'module', plugins: ['typescript'] });
const methods = [];
const events = new Set();
function visit(node, route = []) {
  if (node.type === 'ObjectProperty') route = [...route, node.key.name ?? node.key.value];
  if (node.type === 'CallExpression' && node.callee.type === 'MemberExpression'
    && node.callee.object.name === 'ipcRenderer') {
    const operation = node.callee.property.name;
    const channel = node.arguments[0];
    if (['invoke', 'on'].includes(operation)) {
      if (!channel || channel.type !== 'StringLiteral') throw new Error('Nonliteral preload channel');
      if (operation === 'on') events.add(channel.value);
      else methods.push({ method: route.join('.'), channel: channel.value,
        arguments: node.arguments.slice(1).map(arg => source.slice(arg.start, arg.end)),
        preloadLine: node.loc.start.line });
    }
  }
  for (const value of Object.values(node)) {
    if (Array.isArray(value)) value.forEach(child => { if (child?.type) visit(child, route); });
    else if (value?.type) visit(value, route);
  }
}
visit(tree);
const imports = tree.program.body.filter(node => node.type === 'ImportDeclaration');
if (imports.some(node => node.source.value !== 'electron'
  && node.importKind !== 'type')) throw new Error('Preload gained a runtime dependency');
const importText = imports.filter(node => node.source.value !== 'electron')
  .map(node => source.slice(node.start, node.end)).join('\n');
const declaration = tree.program.body.find(node => node.type === 'VariableDeclaration'
  && node.declarations.some(decl => decl.id.name === 'praxis'));
const initializer = declaration?.declarations[0].init;
if (!initializer || initializer.type !== 'ObjectExpression') throw new Error('Preload contract missing');
const body = source.slice(initializer.start, initializer.end).replaceAll('Electron.IpcRendererEvent', 'unknown');
const generated = `// Generated by scripts/generate-tauri-bridge.cjs. Do not edit.\n${importText}\n\n`
  + `export interface DesktopTransport {\n  invoke(channel: string, ...args: unknown[]): Promise<any>;\n`
  + `  on(channel: string, listener: (...args: any[]) => void): unknown;\n`
  + `  off(channel: string, listener: (...args: any[]) => void): unknown;\n`
  + `  removeListener(channel: string, listener: (...args: any[]) => void): unknown;\n}\n\n`
  + `export function createPraxisBridge(ipcRenderer: DesktopTransport): PraxisIpc {\n  return ${body};\n}\n`;
const manifest = JSON.stringify({ methods, events: [...events].sort() }, null, 2) + '\n';
const outputs = [
  ['renderer/src/host/praxisBridge.generated.ts', generated],
  ['src-tauri/desktop-contract.json', manifest]
];
for (const [file, content] of outputs) {
  const target = path.join(root, file);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) {
      throw new Error(`${file} is stale; run node scripts/generate-tauri-bridge.cjs`);
    }
  } else fs.writeFileSync(target, content);
}
console.log(`Desktop contract: ${methods.length} invocations, ${events.size} event channels`);
